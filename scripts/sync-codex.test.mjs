import { test } from 'node:test'
import assert from 'node:assert/strict'
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
  rmSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import {
  expectedCodexFiles,
  specialistAdapter,
  syncCodex,
} from './sync-codex.mjs'

const role =
  '---\ndescription: Read-only review\nmode: subagent\nsteps: 24\n---\nNever edit, run shell or delegate.\nInspect tests.\n'
test('specialist uses current standalone TOML format and preserves model inheritance', () => {
  const text = specialistAdapter('test-designer', role)
  assert.match(text, /name = "test_designer"/)
  assert.match(text, /developer_instructions = /)
  assert.doesNotMatch(text, /^model\s*=|sandbox_mode\s*=|config_file\s*=/m)
  const value = JSON.parse(text.split('developer_instructions = ')[1].trim())
  assert.match(value, /read-only file inspection/)
  assert.doesNotMatch(value, /Never edit, run shell/)
  assert.throws(() =>
    specialistAdapter('orchestrator', role.replace('subagent', 'primary'))
  )
})

test('sync copies skill resources and creates explicit workflow adapters without writing source', () => {
  const root = mkdtempSync(join(tmpdir(), 'codex-sync-'))
  const put = (path, text) => {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), text)
  }
  const source =
    '---\r\nname: example\r\ndescription: Example\r\n---\r\nKeep contract.\r\n'
  try {
    put('.opencode/skills/example/SKILL.md', source)
    put(
      '.opencode/skills/example/references/data.bin',
      Buffer.from([0, 255, 10])
    )
    put('.opencode/agents/reviewer.md', role)
    put('.opencode/agents/orchestrator.md', role.replace('subagent', 'primary'))
    put(
      '.opencode/commands/test-module.md',
      '---\ndescription: Cover existing behavior\nagent: orchestrator\n---\nCover $ARGUMENTS. No RED.\n'
    )
    const files = expectedCodexFiles(root)
    assert.ok(!files.has('.codex/agents/orchestrator.toml'))
    assert.equal(syncCodex(root).changed.length, 5)
    assert.deepEqual(syncCodex(root, { check: true }).changed, [])
    assert.equal(
      readFileSync(join(root, '.opencode/skills/example/SKILL.md'), 'utf8'),
      source
    )
    assert.equal(
      readFileSync(join(root, '.agents/skills/example/SKILL.md'), 'utf8'),
      source.replace(/\r\n/g, '\n')
    )
    assert.deepEqual(
      readFileSync(join(root, '.agents/skills/example/references/data.bin')),
      Buffer.from([0, 255, 10])
    )
    assert.match(
      readFileSync(
        join(root, '.agents/skills/team-test-module/agents/openai.yaml'),
        'utf8'
      ),
      /allow_implicit_invocation: false/
    )
    put('.agents/skills/example/SKILL.md', '# Drift\n')
    assert.deepEqual(syncCodex(root, { check: true }).changed, [
      '.agents/skills/example/SKILL.md',
    ])
    syncCodex(root)
    put('.codex/agents/user.toml', 'name = "user"\n')
    put(
      '.codex/agents/stale.toml',
      '# Generated by scripts/sync-codex.mjs;\nname = "stale"\n'
    )
    assert.deepEqual(syncCodex(root, { check: true }).stale, [
      '.codex/agents/stale.toml',
    ])
    assert.ok(readFileSync(join(root, '.codex/agents/user.toml'), 'utf8'))
  } finally {
    rmSync(root, { recursive: true, force: true })
  }
})
