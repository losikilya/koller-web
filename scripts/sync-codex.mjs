// Codex adapters for the canonical .opencode starter. Never modify source files.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

const toLf = (text) => text.replace(/\r\n/g, '\n')
const field = (text, key) =>
  text.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim()
const split = (text) => {
  const match = text.match(/^---\n([\s\S]*?)\n---\n?/)
  return match
    ? { meta: match[1], body: text.slice(match[0].length) }
    : { meta: '', body: text }
}
const list = (path) =>
  existsSync(path)
    ? readdirSync(path, { withFileTypes: true }).sort((a, b) =>
        a.name.localeCompare(b.name)
      )
    : []
const toml = (value) => JSON.stringify(value) // TOML basic string escaping for these UTF-8 texts.

export function specialistAdapter(name, source) {
  const { meta, body } = split(toLf(source))
  if (field(meta, 'mode') !== 'subagent')
    throw new Error(`Not a specialist: ${name}`)
  const id = name.replace(/-/g, '_')
  // Codex CLI reads files through shell, unlike OpenCode Read/Grep tools.
  // This is an instruction boundary, not a separate sandbox or tool allowlist.
  const instructions =
    body
      .replace(
        /Never edit, run shell or delegate\./g,
        'Never edit or delegate.'
      )
      .replace(
        /Do not edit, run shell or delegate\./g,
        'Do not edit or delegate.'
      ) +
    '\nCodex adapter: use shell only for read-only file inspection/search when no dedicated read tool exists. Do not run application code, tests, package scripts, network calls or writing commands. Read applicable canonical rules from .opencode/rules as directed by AGENTS.md. Report parent-supplied checks separately from your own inspection. Inherit the session model and permissions; these instructions do not create a read-only sandbox.\n'
  return `# Generated by scripts/sync-codex.mjs; edit the canonical OpenCode agent.\nname = ${toml(
    id
  )}\ndescription = ${toml(
    field(meta, 'description')
  )}\ndeveloper_instructions = ${toml(instructions)}\n`
}

export function workflowAdapter(command, source) {
  const { meta } = split(toLf(source))
  const name = `team-${command}`
  return `---\nname: ${name}\ndescription: ${JSON.stringify(
    `Explicit team workflow ${command}: ${field(meta, 'description')}`
  )}\n---\nRead AGENTS.md and .opencode/commands/${command}.md. Apply that canonical command to the user's current arguments; treat its OpenCode frontmatter as metadata, not Codex configuration. Replace the literal $ARGUMENTS placeholder with the supplied task, change, ticket or module. Never run an OpenCode/Claude CLI to execute this workflow.\n\nThe main Codex session is the sole writer/orchestrator; read .opencode/agents/orchestrator.md for coordination instructions when needed, not as a child-agent definition. Specialist aliases: architect → architect, reviewer → reviewer, test-designer → test_designer, explore → built-in explorer. Delegate sequentially only when the workflow needs it and host policy permits; if independent review cannot run, report it pending instead of inventing PASS.\n\nNames such as /bugfix or /test-module in canonical instructions are workflow labels. In Codex invoke the corresponding $team-* skill or follow that command file directly. Load only relevant procedural skills. Retain the canonical tests-only exception: no production/spec/doc edits, no artificial RED.\n`
}

export function expectedCodexFiles(root) {
  const files = new Map()
  const source = join(root, '.opencode')
  const read = (relative) => toLf(readFileSync(join(source, relative), 'utf8'))
  const copySkill = (sourceDir, targetDir) => {
    for (const entry of list(sourceDir)) {
      if (entry.isSymbolicLink())
        throw new Error(
          `Skill symlinks must be resolved explicitly: ${entry.name}`
        )
      if (entry.isDirectory())
        copySkill(join(sourceDir, entry.name), `${targetDir}/${entry.name}`)
      else
        files.set(
          `${targetDir}/${entry.name}`,
          readFileSync(join(sourceDir, entry.name))
        )
    }
  }
  const skillNames = list(join(source, 'skills'))
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
  for (const name of skillNames) {
    if (!existsSync(join(source, 'skills', name, 'SKILL.md'))) continue
    const target = `.agents/skills/${name}`
    copySkill(join(source, 'skills', name), target)
    files.set(`${target}/SKILL.md`, read(`skills/${name}/SKILL.md`))
  }
  for (const entry of list(join(source, 'commands'))) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue
    const command = entry.name.slice(0, -3)
    const name = `team-${command}`
    if (skillNames.includes(name))
      throw new Error(`Workflow/skill collision: ${name}`)
    files.set(
      `.agents/skills/${name}/SKILL.md`,
      workflowAdapter(command, read(`commands/${entry.name}`))
    )
    // Explicit workflows must not trigger just because a prompt mentions a ticket.
    files.set(
      `.agents/skills/${name}/agents/openai.yaml`,
      'policy:\n  allow_implicit_invocation: false\n'
    )
  }
  for (const entry of list(join(source, 'agents'))) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue
    const text = read(`agents/${entry.name}`)
    if (field(split(text).meta, 'mode') !== 'subagent') continue
    const name = entry.name.slice(0, -3)
    files.set(
      `.codex/agents/${name.replace(/-/g, '_')}.toml`,
      specialistAdapter(name, text)
    )
  }
  return files
}

const marker = '# Generated by scripts/sync-codex.mjs;'
export function syncCodex(root, { check = false } = {}) {
  const expected = expectedCodexFiles(root)
  const changed = []
  for (const [path, content] of expected) {
    const target = join(root, path)
    const same =
      existsSync(target) &&
      (Buffer.isBuffer(content)
        ? readFileSync(target).equals(content)
        : toLf(readFileSync(target, 'utf8')) === content)
    if (same) continue
    changed.push(path)
    if (!check) {
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, content)
    }
  }
  // No deletion, including user-owned skills/agents. Report stale generated files.
  const stale = []
  for (const entry of list(join(root, '.codex/agents'))) {
    const path = `.codex/agents/${entry.name}`
    if (
      entry.isFile() &&
      entry.name.endsWith('.toml') &&
      !expected.has(path) &&
      readFileSync(join(root, path), 'utf8').startsWith(marker)
    )
      stale.push(path)
  }
  for (const entry of list(join(root, '.agents/skills'))) {
    const path = `.agents/skills/${entry.name}/SKILL.md`
    if (
      !entry.isDirectory() ||
      !existsSync(join(root, path)) ||
      expected.has(path)
    )
      continue
    if (
      entry.name.startsWith('team-') &&
      readFileSync(join(root, path), 'utf8').includes(
        'Apply that canonical command'
      )
    )
      stale.push(path)
  }
  return { changed, stale, total: expected.size }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const check = process.argv.includes('--check')
  const result = syncCodex(process.cwd(), { check })
  for (const path of result.changed)
    console.log(`${check ? 'out of sync' : 'updated'}: ${path}`)
  for (const path of result.stale)
    console.log(`stale generated file (remove manually): ${path}`)
  console.log(
    `Codex: ${result.total} files, ${result.changed.length} ${
      check ? 'out of sync' : 'updated'
    }, ${result.stale.length} stale`
  )
  if (check && (result.changed.length || result.stale.length))
    process.exitCode = 1
}
